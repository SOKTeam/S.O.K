"""
Generate the color tokens of the desktop app (src/sok/ui/tokens.py).

The colors of the SOKTeam art direction live in its tokens.json, kept outside
the repository. This script reads it and writes the DARK and LIGHT color
dictionaries that src/sok/ui/theme.py builds its palettes from. Run it again
after every change to tokens.json, never edit tokens.py by hand.

Usage:
    uv run python scripts/make_theme_tokens.py [path/to/tokens.json]

The default path is .impeccable/refs/direction-artistique/tokens.json.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / ".impeccable" / "refs" / "direction-artistique" / "tokens.json"
OUTPUT = ROOT / "src" / "sok" / "ui" / "tokens.py"

ALIAS = re.compile(r"^\{([a-z0-9-]+)\}$")
RGBA = re.compile(r"rgba\([^)]*\)")
PX = re.compile(r"^(\d+)px$")

# Shadows drawn as two 1px lines: the light inside the top edge, then the
# shadow under the bottom edge.
LINE_SHADOWS = ("shadow-key", "shadow-key-primary")

HEADER = '''\
# ===----------------------------------------------------------------------=== #
#
# This source file is part of the S.O.K open source project
#
# Copyright (c) 2026 S.O.K Team
# Licensed under the MIT License
#
# See LICENSE for license information
#
# ===----------------------------------------------------------------------=== #
"""
Tokens of the SOKTeam art direction.

DARK and LIGHT hold the colors of each theme, with the colors of the 1px
light and shadow lines of the buttons ("shadow-key-light", "shadow-key-drop",
and the same for "shadow-key-primary"); RADIUS and SPACE hold sizes in
pixels, the same in both themes.

Generated by scripts/make_theme_tokens.py from tokens.json (version {version}):
do not edit by hand. Aliases such as "accent" are resolved to their color.
"""
'''


def resolve(tokens: dict[str, dict[str, str]], theme: str) -> dict[str, str]:
    """Return every token of a theme with its aliases replaced by colors.

    Args:
        tokens: Token name to {theme id: value}.
        theme: Theme id, "dark" or "light".
    """
    colors = {}
    for name in tokens:
        value = tokens[name][theme]
        seen = {name}
        while match := ALIAS.match(value):
            target = match.group(1)
            if target in seen or target not in tokens:
                raise ValueError(f"Bad alias {value!r} in token {name!r}")
            seen.add(target)
            value = tokens[target][theme]
        colors[name] = value
    return colors


def line_shadows(data: dict, theme: str) -> dict[str, str]:
    """Return the two line colors of each button shadow of a theme.

    "inset 0 1px 0 <light>, 0 1px 0 <drop>" gives "<name>-light" and
    "<name>-drop".
    """
    shadows = {t["name"]: t["value"] for t in data["shadow"]["tokens"]}
    colors = {}
    for name in LINE_SHADOWS:
        light, drop = RGBA.findall(shadows[name][theme])
        colors[f"{name}-light"] = light
        colors[f"{name}-drop"] = drop
    return colors


def sizes(group: dict, prefix: str) -> dict[str, int]:
    """Return the pixel sizes of a token group, without the name prefix."""
    out = {}
    for token in group["tokens"]:
        match = PX.match(token["value"])
        if not match:
            raise ValueError(f"Not a pixel size: {token['name']}")
        out[token["name"].removeprefix(prefix)] = int(match.group(1))
    return out


def render(data: dict) -> str:
    """Return the source of tokens.py for the content of tokens.json."""
    tokens = {t["name"]: t["value"] for t in data["color"]["tokens"]}
    out = [HEADER.format(version=data.get("version", "?"))]
    for theme in ("dark", "light"):
        colors = {**resolve(tokens, theme), **line_shadows(data, theme)}
        out.append(f"\n{theme.upper()} = {{\n")
        for name, value in colors.items():
            out.append(f'    "{name}": "{value}",\n')
        out.append("}\n")
    for name, group, prefix in (
        ("RADIUS", data["radius"], "radius-"),
        ("SPACE", data["spacing"], "space-"),
    ):
        out.append(f"\n{name} = {{\n")
        for key, value in sizes(group, prefix).items():
            out.append(f'    "{key}": {value},\n')
        out.append("}\n")
    return "".join(out)


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    data = json.loads(source.read_text(encoding="utf-8"))
    OUTPUT.write_text(render(data), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} from {source}")


if __name__ == "__main__":
    main()
